CREATE TABLE IF NOT EXISTS `favorites` (
  `favorite_id` bigint UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id` bigint UNSIGNED NOT NULL,
  `target_type` tinyint UNSIGNED NOT NULL,
  `target_id` bigint UNSIGNED NOT NULL,
  `target_name` varchar(255) NULL DEFAULT NULL,
  `target_image` varchar(500) NULL DEFAULT NULL,
  `extra_info` json NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at` datetime NULL DEFAULT NULL,
  PRIMARY KEY (`favorite_id`),
  UNIQUE KEY `uk_user_target` (`user_id`, `target_type`, `target_id`),
  KEY `idx_target` (`target_type`, `target_id`),
  CONSTRAINT `fk_favorites_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `footprints` (
  `footprint_id` bigint UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id` bigint UNSIGNED NOT NULL,
  `poi_id` bigint UNSIGNED NULL DEFAULT NULL,
  `poi_name` varchar(255) NULL DEFAULT NULL,
  `poi_image` varchar(500) NULL DEFAULT NULL,
  `poi_grade` varchar(20) NULL DEFAULT NULL,
  `poi_category` varchar(50) NULL DEFAULT NULL,
  `address` varchar(255) NULL DEFAULT NULL,
  `city_name` varchar(50) NULL DEFAULT NULL,
  `visit_date` date NOT NULL,
  `visit_time` time NULL DEFAULT NULL,
  `type` tinyint UNSIGNED NULL DEFAULT 1,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `deleted_at` datetime NULL DEFAULT NULL,
  PRIMARY KEY (`footprint_id`),
  KEY `idx_user_id_date` (`user_id`, `visit_date`),
  KEY `idx_poi_id` (`poi_id`),
  KEY `idx_city` (`city_name`),
  CONSTRAINT `fk_footprints_user` FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_footprints_poi` FOREIGN KEY (`poi_id`) REFERENCES `poi` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
